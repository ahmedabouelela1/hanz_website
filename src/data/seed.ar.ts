export function localizeCategories(list: CatalogCategory[]): CatalogCategory[] {
  return list.map((c) => ({ ...c, title: categoryTitlesAr[c.slug] ?? c.title }));
}

export function localizeProducts(list: CatalogProduct[]): CatalogProduct[] {
  return list.map((p) => ({ ...p, ...(productsAr[p.slug] ?? {}) }));
}

export function localizePartners(list: Partner[]): Partner[] {
  return list.map((p) => ({ ...p, ...(partnersAr[p.slug] ?? {}) }));
}

export function localizeNews(list: NewsArticle[]): NewsArticle[] {
  return list.map((n) => ({ ...n, ...(newsAr[n.slug] ?? {}) }));
}
